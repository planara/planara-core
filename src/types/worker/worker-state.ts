/**
 * Состояние жизненного цикла воркера рендера.
 *
 * @internal
 */
export enum WorkerState {
  /** Воркер создан и ожидает первого запуска. */
  New = 'new',

  /** Выполняется инициализация модулей. */
  Initializing = 'initializing',

  /** Цикл приостановлен. Модули сохраняют состояние до следующего запуска. */
  Paused = 'paused',

  /** Цикл рендера запущен. */
  Running = 'running',

  /** Инициализация модулей завершилась ошибкой. Повторный запуск запрещён. */
  Failed = 'failed',

  /** Начато освобождение ресурсов. Повторный запуск запрещён. */
  Disposed = 'disposed',
}
