/**
 * Высокоуровневый API для временного включения и отключения пользовательского взаимодействия.
 *
 * @remarks
 * Используется для управления модулями, которые обрабатывают ввод пользователя
 * или реагируют на действия в сцене. Отключение не освобождает ресурсы
 * и не удаляет обработчики событий, а только приостанавливает интерактивную логику.
 *
 * @internal
 * @interface
 */
export interface IInteractionApi {
  /**
   * Включает или отключает пользовательское взаимодействие модуля.
   *
   * @param enabled - `true`, если взаимодействие должно быть включено
   */
  setInteractionEnabled(enabled: boolean): void;

  /**
   * Возвращает текущее состояние пользовательского взаимодействия модуля.
   *
   * @returns `true`, если взаимодействие включено
   */
  isInteractionEnabled(): boolean;
}
