/**
 * API для получения состояния элементов управления сценой.
 *
 * @remarks
 * Предоставляет информацию о текущем состоянии контролов:
 * - взаимодействует ли пользователь с `OrbitControls` (вращение/панорамирование камеры)
 * - взаимодействует ли пользователь с `TransformControls` (перемещение/вращение/масштабирование объекта)
 *
 * Используется модулями (например, {@link RaycastModule}) для определения,
 * нужно ли обрабатывать события ввода, когда пользователь активно взаимодействует с контролами.
 *
 * @see {@link ControlsModule} - реализация этого интерфейса
 *
 * @internal
 * @interface
 */
export interface IControlsStateApi {
  /**
   * Проверяет, взаимодействует ли пользователь с `OrbitControls` в текущий момент.
   *
   * @returns `true`, если пользователь вращает или панорамирует камеру, иначе `false`
   *
   * @remarks
   * OrbitControls отвечает за управление камерой:
   * - левая кнопка мыши + движение — вращение
   * - правая кнопка мыши + движение — панорамирование
   * - колёсико мыши — масштабирование
   *
   * @example
   * ```typescript
   * if (controlsStateApi.isOrbitInteracting()) {
   *   // Не мешаем пользователю крутить камеру
   *   return;
   * }
   * ```
   *
   * @internal
   * @method
   */
  isOrbitInteracting(): boolean;

  /**
   * Проверяет, взаимодействует ли пользователь с `TransformControls` в текущий момент.
   *
   * @returns `true`, если пользователь перемещает/вращает/масштабирует объект через гизмо, иначе `false`
   *
   * @remarks
   * `TransformControls` — это гизмо (стрелки, дуги, квадраты), которое появляется
   * над выделенным объектом.
   *
   * @example
   * ```typescript
   * if (controlsStateApi.isTransformDragging()) {
   *   // Пользователь двигает объект — не обрабатываем hover/click
   *   return;
   * }
   * ```
   *
   * @internal
   * @method
   */
  isTransformDragging(): boolean;
}
